# The following program embodies a collaborative filtering movie recommender system
# using the k-nearest neighbors (KNN) algorithm. The code is structured within a 
# class called CollaborativeFilteringRecommender. Initially, the program loads movie
# rating data from a CSV file using the Surprise library, a tool specifically 
# designed for building recommender systems. The data is then split into training
# and testing sets, following standard machine learning practices.
# 	Subsequently, the recommender system is built using the KNN algorithm,
# more precisely, the KNNBasic implementation from Surprise library. This algorithm
# operates on collaborative filtering principles, inferring user preferences based 
# on patterns observed in similar users' behaviors. The model is trained using the 
# designated training set, where the KNN algorithm's insights are incorporated to 
# enhance its predictive capabilities. After training, the model is utilized to 
# predict user ratings for movies in the testing set, and an optional evaluation 
# step calculates the Root Mean Squared Error (RMSE) to assess the model's accuracy.
# 	To facilitate informed decision-making, the program defines a function that
# extracts and presents the top k movie recommendations for each user. These 
# recommendations leverage estimated ratings generated by the collaborative filtering
# model. The entire process is organized within the main function, which sequentially 
# manages the instantiation of the recommender system class, loading and splitting
# of data, construction and training of the model, prediction generation, evaluation,
# and the display of top movie recommendations. The modular and structured nature 
# of the code enhances readability and facilitates a clear understanding of the 
# collaborative filtering-based movie recommendation process.

import pandas as pd
from surprise import Dataset, Reader, KNNBasic
from surprise.model_selection import train_test_split
from surprise import accuracy

class CollaborativeFilteringRecommender:
    def __init__(self, file_path, k=5):
        self.file_path = file_path
        self.k = k
        self.reader = Reader(rating_scale=(1, 5))
        self.data = None
        self.trainset = None
        self.testset = None
        self.model = None
        self.predictions = None

    def load_data(self):
        # Load the data into the Surprise dataset
        df = pd.read_csv(self.file_path)
        self.data = Dataset.load_from_df(df[['userId', 'movieId', 'rating']], self.reader)

    def split_data(self, test_size=0.2, random_state=42):
        # Split the data into training and testing sets
        self.trainset, self.testset = train_test_split(self.data, test_size=test_size, random_state=random_state)

    def build_model(self, sim_options={'name': 'cosine', 'user_based': True}):
        # Use the KNNBasic algorithm for collaborative filtering
        self.model = KNNBasic(sim_options=sim_options)

        # Train the model
        self.model.fit(self.trainset)

    def make_predictions(self):
        # Make predictions on the test set
        self.predictions = self.model.test(self.testset)

    def evaluate_model(self):
        # Evaluate the model (optional)
        rmse = accuracy.rmse(self.predictions)
        print(f"Root Mean Squared Error (RMSE): {rmse}")

    def get_top_k_recommendations(self):
        # Function to get top k recommendations for each user
        top_k_recommendations = {}
        for uid, iid, true_r, est, _ in self.predictions:
            if uid not in top_k_recommendations:
                top_k_recommendations[uid] = []
            top_k_recommendations[uid].append((iid, est))

        # Sort recommendations for each user by estimated rating
        for uid, user_ratings in top_k_recommendations.items():
            user_ratings.sort(key=lambda x: x[1], reverse=True)
            top_k_recommendations[uid] = user_ratings[:self.k]

        return top_k_recommendations

    def display_top_recommendations(self):
        # Get top k recommendations for each user and display
        top_recommendations = self.get_top_k_recommendations()

        for user_id, recommendations in top_recommendations.items():
            print(f"User {user_id}:")
            for movie_id, estimated_rating in recommendations:
                print(f"  Movie {movie_id}: Estimated Rating {estimated_rating}")
            print()

def main():
    file_path = "/Volumes/KINGSTON/archive/ratings_small.csv"
    recommender = CollaborativeFilteringRecommender(file_path)

    # Load and split the data
    recommender.load_data()
    recommender.split_data()

    # Build and train the model
    recommender.build_model()

    # Make predictions and evaluate the model
    recommender.make_predictions()
    recommender.evaluate_model()

    # Display top recommendations for each user
    recommender.display_top_recommendations()

if __name__ == "__main__":
    main()
